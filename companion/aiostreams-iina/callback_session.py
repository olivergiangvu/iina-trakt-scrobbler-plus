"""Opt-in local AIOStreams playback-return sessions for AIOIINABridge.

No HTTP listener, Trakt writer or AIO DB modifications. Short-lived descriptors
contain a SHA-256 of the exact original signed media URL (never its raw value).
A callback can only originate from a validated return URL + an exact session id.
"""
from __future__ import annotations

import hashlib
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import re
import secrets
import subprocess
import time
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

SESSION_DIR = Path.home() / "Library" / "Application Support" / "AIO-IINA-Bridge" / "sessions"
ALLOWED_ORIGINS = SESSION_DIR.parent / "allowed-origins.txt"
CALLBACK_LOG = Path.home() / "Library" / "Logs" / "AIO-IINA-Bridge.log"


def _audit_result(result: str) -> None:
    """Log only a fixed outcome label; never raw URL, media identity or token."""
    if result not in {"invalid-position", "missing-session", "invalid-session",
                      "expired", "blocked-return", "sent", "failed"}:
        return
    try:
        CALLBACK_LOG.parent.mkdir(parents=True, exist_ok=True)
        with CALLBACK_LOG.open("a", encoding="utf-8") as handle:
            handle.write(datetime.now(timezone.utc).isoformat() +
                         " AIO_CALLBACK_RETURN=" + result + "\\n")
    except OSError:
        pass


SESSION_TTL_MS = 3 * 60 * 60 * 1000
SESSION_RE = re.compile(r"^[a-f0-9]{32}$")
ID_RE = re.compile(r"^[A-Za-z0-9-]{8,128}$")
# AIO externalReturnUrl() uses window.location.pathname verbatim. AIO can
# be served at '/' or from a reverse-proxy base path; it is not Jellyfin Web.
# We require a HashRouter-style AIO item route and strict origin allowlisting.


def media_fingerprint(media_url: str) -> str:
    return hashlib.sha256(media_url.encode("utf-8")).hexdigest()


def _markers(context: str) -> dict[str, str] | None:
    try:
        p = urlsplit(context)
        pairs = parse_qsl(p.query, keep_blank_values=True)
        if "?" in p.fragment:
            pairs += parse_qsl(p.fragment.split("?", 1)[1].replace("?", "&"), keep_blank_values=True)
        result = {}
        for k, v in pairs:
            if k not in ("played", "source"):
                continue
            if k in result and result[k] != v:
                return None
            result[k] = v
        if not all(ID_RE.fullmatch(result.get(k, "")) for k in ("played", "source")):
            return None
        return result
    except (ValueError, TypeError):
        return None


def allowed_origins() -> set[str]:
    out = set()
    try:
        lines = ALLOWED_ORIGINS.read_text(encoding="utf-8").splitlines()
    except OSError:
        lines = []
    lines += os.environ.get("AIO_IINA_CALLBACK_ORIGINS", "").split(",")
    for line in lines:
        line = line.strip().rstrip("/")
        if not line or line.startswith("#"):
            continue
        try:
            u = urlsplit(line)
            if u.scheme not in ("http", "https") or not u.hostname or u.username or u.password:
                continue
            if u.query or u.fragment or u.path not in ("", "/"):
                continue
            out.add(f"{u.scheme}://{u.netloc.lower()}")
        except ValueError:
            continue
    return out


def validated_return_url(context: str, origins: set[str] | None = None) -> str | None:
    if not isinstance(context, str) or len(context) > 4096 or any(ord(c) < 32 for c in context):
        return None
    try:
        p = urlsplit(context)
        if not _markers(context):
            return None
        if p.scheme == "aiostreams":
            return context if p.netloc == "return" and not p.username and not p.password else None
        if p.scheme not in ("http", "https") or not p.hostname or p.username or p.password:
            return None
        # Browser callbacks generated by AIO always contain #/<route>?played=...
        # Markers only in the outer query are insufficient. Keep the exact
        # returned pathname, including '/', without exposing any arbitrary host.
        if not (p.fragment.startswith("/") and "?" in p.fragment):
            return None
        if (not p.path.startswith("/") or "\\" in p.path or
                any(part in (".", "..") for part in p.path.split("/"))):
            return None
        frag_params = parse_qsl(p.fragment.split("?", 1)[1].replace("?", "&"),
                                keep_blank_values=True)
        if not all(any(k == name for k, _ in frag_params)
                   for name in ("played", "source")):
            return None
        origin = f"{p.scheme}://{p.netloc.lower()}"
        if origin not in (allowed_origins() if origins is None else origins):
            return None
        return context
    except (ValueError, TypeError):
        return None


def _mkdir() -> None:
    SESSION_DIR.mkdir(parents=True, exist_ok=True, mode=0o700)
    os.chmod(SESSION_DIR, 0o700)


def _descriptor(session_id: str) -> Path:
    if not SESSION_RE.fullmatch(session_id):
        raise ValueError("invalid_session_id")
    return SESSION_DIR / (session_id + ".json")


def create_session(media: str, context: str, now_ms: int | None = None) -> str | None:
    """Safe opt-in; unapproved context simply disables callback, never playback."""
    if not isinstance(media, str) or not media.startswith(("https://", "http://")):
        return None
    context = validated_return_url(context)
    if context is None:
        return None
    at = int(time.time() * 1000) if now_ms is None else int(now_ms)
    _mkdir()
    session_id = secrets.token_hex(16)
    row = {
        "schema": 1,
        "session": session_id,
        "url_sha256": media_fingerprint(media),
        "return_url": context,
        "issued_at_ms": at,
        "expires_at_ms": at + SESSION_TTL_MS,
    }
    path = _descriptor(session_id)
    fd = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        json.dump(row, handle, separators=(",", ":"))
    return session_id


def discard_session(session_id: str) -> None:
    try:
        _descriptor(session_id).unlink(missing_ok=True)
    except (OSError, ValueError):
        pass


def _callback_url(original: str, position: int) -> str:
    p = urlsplit(original)
    if p.scheme == "aiostreams" or not p.fragment or "?" not in p.fragment:
        pairs = [(k, v) for k, v in parse_qsl(p.query, keep_blank_values=True)
                 if k not in ("position", "finished")]
        pairs.append(("position", str(position)))
        return urlunsplit((p.scheme, p.netloc, p.path, urlencode(pairs), p.fragment))
    before, after = p.fragment.split("?", 1)
    pairs = [(k, v) for k, v in parse_qsl(after.replace("?", "&"), keep_blank_values=True)
             if k not in ("position", "finished")]
    pairs.append(("position", str(position)))
    return urlunsplit((p.scheme, p.netloc, p.path, p.query,
                      before + "?" + urlencode(pairs)))


def complete_session(session_id: str, position: int, *,
                     now_ms: int | None = None, opener=None) -> bool:
    """At-most-once opening. Uses O_EXCL marker; never claims arbitrary context."""
    if type(position) is not int or position < 1 or position > 604800:
        _audit_result("invalid-position")
        return False
    try:
        path = _descriptor(session_id)
        if path.stat().st_size > 8192 or path.is_symlink():
            _audit_result("invalid-session")
            return False
        row = json.loads(path.read_text(encoding="utf-8"))
        at = int(time.time() * 1000) if now_ms is None else int(now_ms)
        if row.get("schema") != 1 or row.get("session") != session_id:
            _audit_result("invalid-session")
            return False
        if not (int(row["issued_at_ms"]) <= at <= int(row["expires_at_ms"])):
            _audit_result("expired")
            return False
        context = validated_return_url(row.get("return_url"))
        if not context:
            _audit_result("blocked-return")
            return False
        stamp = SESSION_DIR / (session_id + ".sent")
        fd = os.open(stamp, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
        os.close(fd)
        target = _callback_url(context, position)
        if opener is None:
            subprocess.run(["/usr/bin/open", "-g", target], check=True,
                           stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                           stderr=subprocess.DEVNULL, timeout=8)
        else:
            opener(target)
        _audit_result("sent")
        return True
    except FileNotFoundError:
        _audit_result("missing-session")
        return False
    except (OSError, ValueError, KeyError, TypeError, subprocess.SubprocessError):
        _audit_result("failed")
        return False


def main(argv=None):
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--complete", help="Opaque 32-char session id; never a URL")
    parser.add_argument("--position", type=int)
    args = parser.parse_args(argv)
    if args.complete and args.position is not None:
        return 0 if complete_session(args.complete, args.position) else 1
    return 64


if __name__ == "__main__":
    raise SystemExit(main())
