const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const path = require("node:path");
const html=fs.readFileSync(path.resolve(__dirname,"../sidebar.html"),"utf8");
const main=fs.readFileSync(path.resolve(__dirname,"../main.js"),"utf8");
const script=html.match(/<script>([\s\S]*?)<\/script>/);
assert.ok(script,"sidebar inline JavaScript must exist");
new vm.Script(script[1],{filename:"sidebar.html"});
assert.match(html,/id="correction-kind"/);
assert.match(html,/<option value="episode">TV Series \/ Episode<\/option>/);
assert.match(html,/<option value="movie">Movie<\/option>/);
assert.match(html,/var episodeMode = correction\.kind === "episode"/);
assert.match(html,/send\("change_correction_kind",\s*\{kind:kind\}\)/);
assert.match(main,/sidebar\.onMessage\("change_correction_kind"/);
assert.match(main,/correctionMedia\.searchMedia\(currentMedia\.mediaInfo/);
assert.match(main,/correctionMedia\.selectMedia\(originalMediaInfo/);
assert.match(main,/var mediaForLookup = correctionMedia\.searchMedia/);
assert.match(main,/var initialKind = correctionMedia\.preferredKind/);
console.log("manual type switching and S/E editor UI contract tests passed");