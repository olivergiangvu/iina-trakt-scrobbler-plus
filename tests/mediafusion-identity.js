const assert=require("node:assert/strict");
const m=require("../mediafusion-identity.js");
const token="D-SECRETPRIVATE";
const hash="f6738693f7d3d0aed66035633895c6a10751e867";
const u="https://mediafusion.elfhosted.com/streaming_provider/"+token+"/playback/torbox/"+hash+"/2/8";
const x=m.fromUrl(u);
assert.equal(x.season,2);assert.equal(x.episode,8);assert.equal(x.provider,"torbox");
assert.equal(x.kind,"episode");assert.match(x.fingerprint,/^[a-f0-9]{16}$/);
assert.ok(!JSON.stringify(x).includes("SECRET"));
assert.ok(!JSON.stringify(x).includes(hash));
assert.equal(m.fromUrl(u.replace("/2/8","/2/0")),null);
assert.equal(m.fromUrl(u.replace("mediafusion.elfhosted.com","evil.example")),null);
assert.equal(m.fromUrl("https://mediafusion.elfhosted.com/streaming_provider/"+token+"/playback/torbox/"+hash),null);
const files={};let now=1000000000;
const cache=m.create({exists:p=>Object.hasOwn(files,p),read:p=>files[p],write:(p,v)=>files[p]=v},{now:()=>now});
assert.equal(cache.find(x),null);
assert.equal(cache.remember(x,4242,"The Legend of Vox Machina"),true);
assert.equal(cache.find(x).title,"The Legend of Vox Machina");
assert.equal(cache.find({...x,episode:7}).trakt,4242,"other episode of same season pack");
assert.equal(cache.find({...x,season:3}),null,"no cross-season");
assert.ok(!JSON.stringify(files).includes(hash));
assert.ok(!JSON.stringify(files).includes(token));
now+=61*24*60*60*1000;assert.equal(cache.find(x),null,"TTL");
console.log("MediaFusion S/E route and opt-in season pack cache tests passed");